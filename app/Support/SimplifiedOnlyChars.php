    public static function findIn(string $text): array {
        if (self::$set === null) {
            self::$set = array_fill_keys(preg_split('//u', self::CHARS, -1, PREG_SPLIT_NO_EMPTY) ?: [], true);
        }

        $found = [];
        foreach (preg_split('//u', $text, -1, PREG_SPLIT_NO_EMPTY) ?: [] as $char) {
            if (isset(self::$set[$char]) && !isset($found[$char])) {
                $found[$char] = true;
            }
        }

        return array_keys($found);
    }
